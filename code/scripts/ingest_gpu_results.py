#!/usr/bin/env python3
"""Workstation-side ingest of GPU results and paper-table generation.

Usage:
    python3 scripts/ingest_gpu_results.py --tar gpu_results.tar.gz
    python3 scripts/ingest_gpu_results.py            # just re-generate the table

Steps:
  1. Unpack gpu_results.tar.gz into results/real/ (never overwrites a
     newer local file without --force).
  2. Validate every full_*.json: required fields, metric ranges, and the
     full-epoch protocol markers (max_batches == 0, epochs == 30).
  3. Print the completed full-protocol matrix (which cells exist).
  4. Generate full_protocol_table.tex (HR@20 / MRR@20, gray -- for any
     missing cell) ready to be \\input{} from the paper.
"""
import argparse
import json
import shutil
import sys
import tarfile
from pathlib import Path

P = Path(__file__).resolve().parents[1]
OUT = P / "results" / "real"
DATASETS = ["diginetica", "gowalla", "yoochoose_quarter"]
DS_LABEL = {"diginetica": "Diginetica", "gowalla": "Gowalla",
            "yoochoose_quarter": "Yoo-1/4"}
MODELS = ["itemknn", "narm", "srgnn", "gcegnn", "mplignn_L1", "mplignn"]
M_LABEL = {"itemknn": "Item-KNN", "narm": "NARM", "srgnn": "SR-GNN",
           "gcegnn": "GCE-GNN", "mplignn_L1": "MPLI-GNN ($L{=}1$)",
           "mplignn": "MPLI-GNN ($L{=}2$)"}


def ingest(tar: Path, force=False):
    n, bad = 0, []
    with tarfile.open(tar) as tf:
        for m in tf.getmembers():
            if not m.name.startswith("results/real/full_"):
                continue
            dest = P / m.name
            if dest.exists() and not force:
                continue
            dest.parent.mkdir(parents=True, exist_ok=True)
            with tf.extractfile(m) as src, open(dest, "wb") as dst:
                shutil.copyfileobj(src, dst)
            n += 1
    print(f"extracted {n} files from {tar.name}")
    return bad


def validate():
    ok, bad = 0, []
    for f in sorted(OUT.glob("full_*.json")):
        try:
            r = json.loads(f.read_text())
            t = r["test"]
            for k in ("HR@20", "MRR@20", "NDCG@20"):
                assert 0.0 <= t[k] <= 1.0, f"{k} out of range in {f.name}"
            if r.get("model") != "itemknn":   # closed-form, no epochs
                assert r.get("max_batches") == 0, f"not full-epoch: {f.name}"
                assert r.get("epochs", 30) == 30, f"epoch count changed: {f.name}"
            ok += 1
        except Exception as e:
            bad.append((f.name, str(e)))
    print(f"validated {ok} full_*.json files")
    for name, err in bad:
        print(f"  INVALID {name}: {err}")
    return bad


def matrix():
    cells = {}
    for d in DATASETS:
        for m in MODELS:
            f = OUT / f"full_{m}_{d}.json"
            if f.exists():
                t = json.loads(f.read_text())["test"]
                cells[(d, m)] = (100 * t["HR@20"], 100 * t["MRR@20"])
    hdr = "model".ljust(12) + "".join(DS_LABEL[d].ljust(22) for d in DATASETS)
    print("\nfull-epoch matrix (HR@20/MRR@20 %):")
    print(hdr)
    for m in MODELS:
        row = M_LABEL[m].split(" ")[0].ljust(12)
        for d in DATASETS:
            row += (f"{cells[(d,m)][0]:.2f}/{cells[(d,m)][1]:.2f}").ljust(22) \
                if (d, m) in cells else "--".ljust(22)
        print(row)
    done = len(cells)
    print(f"completed: {done}/{len(DATASETS) * len(MODELS)} cells")
    return cells


def table(cells):
    lines = [
        "% Auto-generated by scripts/ingest_gpu_results.py -- DO NOT hand-edit",
        "\\begin{table*}[t]",
        "\\caption{Full-epoch protocol (no batch cap, 30 epochs, patience 5):",
        "HR@20 / MRR@20 (\\%). Baselines use their published size and learning",
        "rate; MPLI-GNN uses its design configuration. Missing cells are runs",
        "still in progress and are never fabricated.}",
        "\\label{tab:fullepoch}",
        "\\centering\\small\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{l cc cc cc}",
        "\\toprule",
        " & \\multicolumn{2}{c}{Diginetica} & \\multicolumn{2}{c}{Gowalla}"
        " & \\multicolumn{2}{c}{Yoo-1/4} \\\\",
        "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}",
        "Method & HR & MRR & HR & MRR & HR & MRR \\\\",
        "\\midrule",
    ]
    for m in MODELS:
        row = [M_LABEL[m]]
        for d in DATASETS:
            if (d, m) in cells:
                h, r = cells[(d, m)]
                row += [f"{h:.2f}", f"{r:.2f}"]
            else:
                row += ["\\textcolor{gray}{--}"] * 2
        lines.append(" & ".join(row) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    out = P.parent / "v1" / "full_protocol_table.tex"
    out.write_text("\n".join(lines))
    print(f"wrote {out.relative_to(P.parent)}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tar", type=Path, default=None)
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()
    if args.tar and args.tar.exists():
        ingest(args.tar, args.force)
    validate()
    table(matrix())


if __name__ == "__main__":
    main()
